import Foundation
import Testing
@testable import TimeTrackerCore

struct OfflineSyncContractTests {
    @Test func localLogRetriesAgainstConfiguredAPIWithStableIdempotencyKey() async throws {
        guard
            let rawURL = ProcessInfo.processInfo.environment["TRACKER_E2E_API_URL"],
            let username = ProcessInfo.processInfo.environment["TRACKER_E2E_USERNAME"],
            let password = ProcessInfo.processInfo.environment["TRACKER_E2E_PASSWORD"],
            let baseURL = URL(string: rawURL)
        else {
            return
        }

        let client = TrackerAPIClient(baseURL: baseURL)
        let token = try await client.login(username: username, password: password).accessToken
        let startedAt = Date.now.addingTimeInterval(-600)
        let log = LocalActivityLog(
            title: "iOS offline sync contract \(UUID().uuidString)",
            notes: "Generated by OfflineSyncContractTests",
            startedAt: startedAt,
            endedAt: Date.now,
            categoryIDs: [],
            visibility: .private
        )

        let firstReceipt = try await client.createLog(log, accessToken: token)
        let retryReceipt = try await client.createLog(log, accessToken: token)

        #expect(firstReceipt.id == retryReceipt.id)
        #expect(firstReceipt.idempotencyKey == log.idempotencyKey)
        #expect(retryReceipt.idempotencyKey == log.idempotencyKey)
        #expect(firstReceipt.created != retryReceipt.created)
    }
}
